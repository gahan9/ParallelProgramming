#!/usr/bin/env python3
"""Feedback loops made visible: a recommender that trains on its own outputs.

Standard library only (math, random, argparse, sys). No numpy.

The danger this simulates
-------------------------
A recommender's next training set is generated by its current recommendations.
Items it does not show get no impressions, so they get no clicks, so their
estimated quality never improves, so they are never shown. The loop closes.
The model does not become "wrong" in any way a drift dashboard can see -- its
inputs look fine, its predictions look confident, and its click-through rate
may even RISE, because it is only ever measured on the items it chose.

What collapses instead is catalogue coverage and the ability to ever discover
that a better item exists. That is invisible unless you measure it directly,
which is the point of this tool.

The fix is exploration: show a small random fraction of traffic something the
model did not pick, log the propensity, and you retain both the data to
correct your estimates off-policy and the ability to find items the model was
wrong about.

EVERY NUMBER BELOW IS SIMULATED. The model is a Beta-posterior bandit over a
fixed catalogue; real recommenders are far more complex. The qualitative
result -- coverage collapse without exploration -- is robust to the details
and is documented in the literature (Chaney et al. 2018; Bottou et al. 2013).
"""

from __future__ import annotations

import argparse
import math
import random
import sys


# --------------------------------------------------------------------------
# Metrics
# --------------------------------------------------------------------------


def gini(values):
    """Gini coefficient of an impression distribution. 0 = uniform, 1 = one item takes all."""
    ordered = sorted(values)
    n = len(ordered)
    total = sum(ordered)
    if n == 0 or total == 0:
        return 0.0
    weighted = sum((i + 1) * v for i, v in enumerate(ordered))
    return (2.0 * weighted) / (n * total) - (n + 1.0) / n


def top_share(values, k):
    """Share of all impressions taken by the k most-shown items."""
    total = sum(values)
    if total == 0:
        return 0.0
    return sum(sorted(values, reverse=True)[:k]) / total


# --------------------------------------------------------------------------
# Simulation
# --------------------------------------------------------------------------


def simulate(seed, catalogue, rounds, users_per_round, slots, epsilon,
             prior_strength, quality_alpha, quality_beta):
    """One run of the closed feedback loop.

    The model refreshes once per round -- the usual production cadence -- so
    within a round every user sees the same ranking, modulo exploration.
    """
    rng = random.Random(seed)

    # True click probability of each item. Unknown to the model, fixed for the run.
    true_quality = [rng.betavariate(quality_alpha, quality_beta) for _ in range(catalogue)]
    best_items = set(sorted(range(catalogue), key=lambda i: -true_quality[i])[:10])

    impressions = [0] * catalogue
    clicks = [0] * catalogue

    history = []
    ever_shown = set()

    for round_index in range(rounds):
        # Model refresh: Beta posterior mean over observed data only. Items with
        # no impressions sit at the prior, which is exactly the trap -- the model
        # is not "wrong" about them, it is uninformed, and it has no mechanism
        # to become informed.
        estimate = [(clicks[i] + prior_strength * 0.5) / (impressions[i] + prior_strength)
                    for i in range(catalogue)]
        ranking = sorted(range(catalogue), key=lambda i: -estimate[i])
        exploit_slate = ranking[:slots]

        round_shown = set()
        round_clicks = 0
        round_impressions = 0
        round_quality = 0.0

        for _ in range(users_per_round):
            for slot in range(slots):
                if rng.random() < epsilon:
                    item = rng.randrange(catalogue)      # logged propensity: epsilon/catalogue
                else:
                    item = exploit_slate[slot]           # logged propensity: 1 - epsilon
                impressions[item] += 1
                round_impressions += 1
                round_shown.add(item)
                ever_shown.add(item)
                round_quality += true_quality[item]
                if rng.random() < true_quality[item]:
                    clicks[item] += 1
                    round_clicks += 1

        history.append({
            "round": round_index,
            "ctr": round_clicks / round_impressions if round_impressions else 0.0,
            "round_coverage": len(round_shown) / catalogue,
            "cumulative_coverage": len(ever_shown) / catalogue,
            "gini": gini(impressions),
            "top10_share": top_share(impressions, 10),
            "mean_true_quality_shown": round_quality / round_impressions if round_impressions else 0.0,
        })

    final_estimate = [(clicks[i] + prior_strength * 0.5) / (impressions[i] + prior_strength)
                      for i in range(catalogue)]
    discovered = len(best_items & ever_shown)
    oracle_quality = sum(sorted(true_quality, reverse=True)[:slots]) / slots

    return {
        "epsilon": epsilon,
        "history": history,
        "true_quality": true_quality,
        "impressions": impressions,
        "estimate": final_estimate,
        "ever_shown": ever_shown,
        "best_items": best_items,
        "discovered_top10": discovered,
        "oracle_slate_quality": oracle_quality,
        "never_shown": catalogue - len(ever_shown),
    }


# --------------------------------------------------------------------------
# Reporting
# --------------------------------------------------------------------------


def sparkline(values, lo=0.0, hi=1.0, width=40):
    levels = " .:-=+*#%@"
    if not values:
        return ""
    step = max(1, len(values) // width)
    sampled = values[::step][:width]
    out = []
    for v in sampled:
        scaled = 0.0 if hi <= lo else (v - lo) / (hi - lo)
        scaled = max(0.0, min(0.999, scaled))
        out.append(levels[int(scaled * len(levels))])
    return "".join(out)


def print_run(result, catalogue):
    history = result["history"]
    first, last = history[0], history[-1]
    print()
    print("  exploration epsilon = %.0f%%" % (100 * result["epsilon"]))
    print("    %-34s %10s %10s" % ("metric", "round 1", "round %d" % len(history)))
    print("    %-34s %10s %10s" % ("-" * 34, "-" * 10, "-" * 10))
    print("    %-34s %9.3f  %9.3f" % ("observed CTR", first["ctr"], last["ctr"]))
    print("    %-34s %9.1f%% %9.1f%%" % ("catalogue coverage this round",
                                         100 * first["round_coverage"], 100 * last["round_coverage"]))
    print("    %-34s %9.1f%% %9.1f%%" % ("cumulative coverage",
                                         100 * first["cumulative_coverage"],
                                         100 * last["cumulative_coverage"]))
    print("    %-34s %9.3f  %9.3f" % ("impression Gini (1 = winner-take-all)",
                                      first["gini"], last["gini"]))
    print("    %-34s %9.1f%% %9.1f%%" % ("top-10 items' impression share",
                                         100 * first["top10_share"], 100 * last["top10_share"]))
    print("    %-34s %9.3f  %9.3f" % ("mean TRUE quality of shown items",
                                      first["mean_true_quality_shown"],
                                      last["mean_true_quality_shown"]))
    print("    %-34s %10s" % ("items never shown, of %d" % catalogue, result["never_shown"]))
    print("    %-34s %8d/10" % ("of the true top 10, discovered", result["discovered_top10"]))
    print("    %-34s %9.3f" % ("oracle best-slate quality", result["oracle_slate_quality"]))
    print()
    print("    coverage over time  [%s]"
          % sparkline([h["round_coverage"] for h in history], 0.0, 1.0))
    print("    observed CTR        [%s]"
          % sparkline([h["ctr"] for h in history], 0.0, 1.0))


def estimation_bias(result, catalogue):
    """How wrong is the model about the items it stopped showing?"""
    never = [i for i in range(catalogue) if result["impressions"][i] == 0]
    if not never:
        return None
    true_mean = sum(result["true_quality"][i] for i in never) / len(never)
    est_mean = sum(result["estimate"][i] for i in never) / len(never)
    best_missed = max(result["true_quality"][i] for i in never)
    return {"count": len(never), "true_mean": true_mean, "est_mean": est_mean,
            "best_missed": best_missed}


def run(args):
    if args.catalogue < args.slots:
        raise ValueError("--catalogue (%d) must be at least --slots (%d)"
                         % (args.catalogue, args.slots))
    if not all(0.0 <= e <= 1.0 for e in args.epsilons):
        raise ValueError("every --epsilons value must be between 0 and 1")

    print("=" * 84)
    print("FEEDBACK LOOP SIMULATION -- SIMULATED DATA, seed %d" % args.seed)
    print("=" * 84)
    print("  catalogue %d items | %d rounds | %d users/round | %d slots | model refresh each round"
          % (args.catalogue, args.rounds, args.users, args.slots))
    print("  Item true click-rates are drawn once from Beta(%.1f, %.1f) and never change."
          % (args.quality_alpha, args.quality_beta))
    print("  NOTHING about the world drifts in this simulation. Every effect you see below")
    print("  is caused by the model training on data its own choices produced.")

    results = []
    for epsilon in args.epsilons:
        result = simulate(args.seed, args.catalogue, args.rounds, args.users, args.slots,
                          epsilon, args.prior_strength, args.quality_alpha, args.quality_beta)
        results.append(result)
        print_run(result, args.catalogue)

    print()
    print("=" * 84)
    print("SIDE BY SIDE")
    print("=" * 84)
    print("  %-12s %10s %12s %12s %12s %14s"
          % ("epsilon", "final CTR", "coverage", "Gini", "never shown", "top-10 found"))
    print("  %-12s %10s %12s %12s %12s %14s"
          % ("-" * 12, "-" * 10, "-" * 12, "-" * 12, "-" * 12, "-" * 14))
    for r in results:
        last = r["history"][-1]
        print("  %-12s %10.3f %11.1f%% %12.3f %12d %11d/10"
              % ("%.0f%%" % (100 * r["epsilon"]), last["ctr"],
                 100 * last["cumulative_coverage"], last["gini"],
                 r["never_shown"], r["discovered_top10"]))

    print()
    print("WHAT THIS SHOWS")
    print("-" * 84)

    greedy = results[0]
    bias = estimation_bias(greedy, args.catalogue)
    if bias:
        print("  1. The greedy loop never showed %d of %d items. For those items the model's"
              % (bias["count"], args.catalogue))
        print("     estimate averages %.3f while their true click-rate averages %.3f, and the"
              % (bias["est_mean"], bias["true_mean"]))
        print("     best one it never showed has a true rate of %.3f. The model is not wrong"
              % bias["best_missed"])
        print("     about them -- it is UNINFORMED, and it has no mechanism to become informed.")
    else:
        print("  1. With these parameters the greedy loop still covered the catalogue. Try")
        print("     --rounds 120 --slots 3 --catalogue 500 to reproduce the collapse.")

    print("  2. Observed CTR is not a warning signal. It is measured only on items the model")
    print("     chose, so a narrowing model can look like an improving one. This is why CTR")
    print("     alone is a dangerous production metric for a recommender.")
    print("  3. Coverage is the metric that moves: %.1f%% greedy vs %.1f%% at the largest"
          % (100 * greedy["history"][-1]["cumulative_coverage"],
             100 * results[-1]["history"][-1]["cumulative_coverage"]))
    print("     exploration rate here. It does not appear on any standard service dashboard,")
    print("     and it is not a 'model quality' metric in the usual sense. You have to decide")
    print("     to measure it.")
    print("     Read Gini carefully, though -- it is NOT a coverage proxy. Exploration can")
    print("     RAISE it, because sprinkling one impression each across hundreds of tail items")
    print("     is itself an unequal distribution. Coverage and long-tail share answer the")
    print("     question you actually care about; Gini answers a different one.")

    ctr_delta = results[-1]["history"][-1]["ctr"] - greedy["history"][-1]["ctr"]
    if ctr_delta >= 0:
        print("  4. In THIS run exploration did not even cost short-term CTR: %.3f at %.0f%%"
              % (results[-1]["history"][-1]["ctr"], 100 * results[-1]["epsilon"]))
        print("     exploration versus %.3f for the greedy loop. The greedy policy locked onto"
              % greedy["history"][-1]["ctr"])
        print("     a suboptimal set early and could never discover it had done so, which is")
        print("     the whole failure mode. Do not generalise the sign of this result -- with a")
        print("     different seed or a stronger prior, exploration usually does cost a little.")
        print("     Generalise the mechanism, not the number.")
    else:
        print("  4. Exploration cost %.3f of CTR (%.1f%% relative) and bought the coverage above."
              % (-ctr_delta, 100 * -ctr_delta / greedy["history"][-1]["ctr"]))
        print("     That is the trade, and it should be an explicit, reviewed decision rather")
        print("     than an accident of implementation.")
    print()
    print("  COUNTERMEASURES this simulation is an argument for:")
    print("    * Exploration: epsilon-greedy, Thompson sampling, or an explicit random slate")
    print("      slot. Thompson sampling explores far more efficiently than epsilon-greedy;")
    print("      epsilon is used here because it is the clearest to reason about.")
    print("    * LOG THE PROPENSITY of every impression. Without it you cannot compute an")
    print("      unbiased off-policy estimate later, and you will not be able to answer")
    print("      'would the other model have done better?' from logs alone.")
    print("    * Keep a small randomized holdout population, permanently unaffected by the")
    print("      model, as ground truth for what unbiased behaviour looks like.")
    print("    * Monitor catalogue coverage and long-tail impression share as first-class")
    print("      production metrics, with alerts, not as an annual analysis.")


def build_parser():
    p = argparse.ArgumentParser(
        description="Seeded simulation of a recommender training on its own recommendations.")
    p.add_argument("--seed", type=int, default=20240729)
    p.add_argument("--catalogue", type=int, default=400, help="number of items")
    p.add_argument("--rounds", type=int, default=80, help="model refresh cycles")
    p.add_argument("--users", type=int, default=300, help="users per round")
    p.add_argument("--slots", type=int, default=4, help="items recommended per user")
    p.add_argument("--epsilons", type=float, nargs="+", default=[0.0, 0.02, 0.10],
                   help="exploration fractions to compare")
    p.add_argument("--prior-strength", type=float, default=4.0,
                   help="Beta prior pseudo-counts for an unseen item")
    p.add_argument("--quality-alpha", type=float, default=1.5)
    p.add_argument("--quality-beta", type=float, default=6.0)
    return p


def main(argv=None):
    if sys.version_info < (3, 8):
        sys.stderr.write("ERROR: this tool needs Python 3.8 or newer.\n")
        return 2
    args = build_parser().parse_args(argv)
    try:
        run(args)
    except ValueError as exc:
        sys.stderr.write("ERROR: %s\n" % exc)
        sys.stderr.write("Run with -h for usage.\n")
        return 2
    except KeyboardInterrupt:
        sys.stderr.write("\nInterrupted.\n")
        return 130
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
